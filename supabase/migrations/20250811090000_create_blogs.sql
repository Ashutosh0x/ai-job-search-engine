-- Ensure the table is part of the realtime publication
do $$
declare exists_in_pub boolean;
begin
  select exists(
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'blogs'
  ) into exists_in_pub;
  if not exists_in_pub then
    execute 'alter publication supabase_realtime add table public.blogs';
  end if;
exception when others then
  -- ignore if publication does not exist in local dev or already configured
  null;
end $$;


